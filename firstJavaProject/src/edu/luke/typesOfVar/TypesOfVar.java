package edu.luke.typesOfVar;

public class TypesOfVar {
    public static void main(String[] args) {
        int x = 10; // 32 bits Preferred
        long y = 1000l; // 64 bits Necessary for biggest numbers, every place L at the end
        float z = 10.5f; // 32 bits every place F at the end
        double w = 10.5; // 64 bits Preferred
        char c = 'a'; // 16 bits
        boolean b = true; // 1 bit


        //FINAL VARIABLES
        final double VALUE_OF_PI = 3.141592653589793238462643383279502884;
    }
}
